/**
 * Type generation from a schema DSL or normalized DatabaseSchema.
 *
 * Produces a `.d.ts` source string that gives full row-type inference
 * across the chain. The user types their `db` as the generated `XxxOrm`
 * interface and every read, write, and computed projection narrows
 * correctly.
 *
 * Output shape:
 *
 *   import type { Table } from '@kuratchi/kunii';
 *
 *   export interface UsersRow {
 *     id: number;
 *     email: string;
 *     name: string | null;
 *     meta: any | null;       // JSON columns default to `any | null`
 *     deleted_at: number | null;
 *   }
 *
 *   export interface AppOrm {
 *     users: Table<UsersRow>;
 *     posts: Table<PostsRow>;
 *     batch(...): Promise<BatchResult>;
 *   }
 *
 * Usage:
 *
 *   import { generateTypes } from '@kuratchi/kunii/codegen';
 *   const dts = generateTypes(schema, { ormName: 'AppOrm' });
 *   await fs.writeFile('src/db-types.d.ts', dts);
 *
 * Limitations (intentional):
 *   - JSON column shapes default to `any | null`. Override per-call by
 *     casting the row type, or pass `jsonShapes: { users: { meta: 'UserMeta' } }`
 *     to the generator and the named TS type is referenced inline.
 *   - Foreign keys don't auto-narrow related rows — `Table<UsersRow>`
 *     doesn't know about `posts`. Relations work at runtime but their
 *     types are still `any` on the chain. (Future Phase E.)
 */

import { ensureNormalizedSchema, type DatabaseSchema, type Column } from './schema.js';
import type { SchemaDsl } from './types.js';

export type GenerateTypesOptions = {
  /**
   * Name of the top-level interface mapping table names to `Table<Row>`.
   * Defaults to `<SchemaName>Orm` derived from `schema.name`, PascalCased.
   */
  ormName?: string;
  /**
   * Per-table JSON column shape overrides. The provided value is the
   * exact TS expression used for the field — typically a referenced
   * named type that the consumer imports separately.
   *
   * Example:
   *   jsonShapes: { users: { preferences: "import('./types').UserPrefs" } }
   */
  jsonShapes?: Record<string, Record<string, string>>;
  /**
   * Module specifier used for the `Table` import. Defaults to
   * `'@kuratchi/kunii'`; override for monorepo-internal or legacy codegen.
   */
  importFrom?: string;
};

/**
 * Generate a `.d.ts` source string from a schema.
 *
 * Accepts both `SchemaDsl` (DSL form) and `DatabaseSchema` (normalized).
 */
export function generateTypes(
  schema: SchemaDsl | DatabaseSchema,
  options: GenerateTypesOptions = {}
): string {
  const normalized = ensureNormalizedSchema(schema);
  const ormName = options.ormName ?? `${pascal(normalized.name)}Orm`;
  const importFrom = options.importFrom ?? '@kuratchi/kunii';
  const jsonShapes = options.jsonShapes ?? {};

  const blocks: string[] = [];
  blocks.push(`// AUTO-GENERATED by kunii - do not edit by hand.`);
  blocks.push(`// Source schema: ${normalized.name}` + (normalized.version != null ? ` v${normalized.version}` : ''));
  blocks.push('');
  blocks.push(`import type { Table, BatchCallback, BatchResult } from '${importFrom}';`);
  blocks.push('');

  // One `XxxRow` interface per table.
  for (const table of normalized.tables) {
    const rowName = `${pascal(table.name)}Row`;
    blocks.push(`export interface ${rowName} {`);
    for (const col of table.columns) {
      const tsType = columnTsType(col, jsonShapes[table.name]?.[col.name]);
      blocks.push(`  ${quoteFieldKey(col.name)}: ${tsType};`);
    }
    blocks.push('}');
    blocks.push('');
  }

  // Top-level interface mapping table names → Table<Row>.
  blocks.push(`export interface ${ormName} {`);
  for (const table of normalized.tables) {
    const rowName = `${pascal(table.name)}Row`;
    blocks.push(`  ${quoteFieldKey(table.name)}: Table<${rowName}>;`);
  }
  blocks.push(`  batch(callback: BatchCallback): Promise<BatchResult>;`);
  blocks.push(`}`);
  blocks.push('');

  return blocks.join('\n');
}

// ── Helpers ────────────────────────────────────────────────

/**
 * Map a column's storage type + mode + nullability to a TS type expression.
 *
 * - PRIMARY KEY columns are non-null even without `not null` (SQLite
 *   nullable PKs are a footgun we don't model).
 * - `boolean` mode → `boolean | null`.
 * - `timestamp_ms` → `number | null` (epoch ms).
 * - `json` → user override or `any | null` fallback.
 */
function columnTsType(col: Column, jsonOverride?: string): string {
  const required = !!col.notNull || !!col.primaryKey;

  let base: string;
  if (col.type === 'json') {
    base = jsonOverride ?? 'any';
  } else if (col.mode === 'boolean') {
    base = 'boolean';
  } else if (col.mode === 'timestamp_ms') {
    base = 'number';
  } else if (col.enum && col.enum.length > 0) {
    base = col.enum.map((v) => JSON.stringify(v)).join(' | ');
  } else {
    switch (col.type) {
      case 'integer':
        base = 'number';
        break;
      case 'real':
        base = 'number';
        break;
      case 'blob':
        base = 'ArrayBuffer';
        break;
      case 'text':
      default:
        base = 'string';
    }
  }

  return required ? base : `${base} | null`;
}

/** Convert a snake/kebab/camel name to PascalCase. */
function pascal(s: string): string {
  return s
    .replace(/[-_\s]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

/**
 * Decide whether a TS object key needs to be quoted. Identifiers without
 * special chars are bare; anything else is wrapped in single quotes.
 */
function quoteFieldKey(name: string): string {
  if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) return name;
  return `'${name.replace(/'/g, "\\'")}'`;
}
